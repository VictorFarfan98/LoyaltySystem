-- Only the branch picker has a direct, caller-scoped read interface in P01.
create schema loyalty authorization postgres;
revoke all on schema loyalty from public, anon, authenticated, service_role;

create table loyalty.businesses (
  id bigint generated by default as identity primary key,
  name text not null check (btrim(name) <> ''),
  status text not null default 'active' check (status in ('active', 'inactive', 'closed'))
);

create table public.branches (
  business_id bigint not null references loyalty.businesses,
  id bigint generated by default as identity,
  name text not null check (btrim(name) <> ''),
  active boolean not null default true,
  primary key (business_id, id)
);

create table loyalty.staff_memberships (
  user_id uuid primary key references auth.users,
  business_id bigint not null references loyalty.businesses,
  role text not null check (role in ('owner', 'manager', 'branch_staff', 'marketing')),
  active boolean not null default true,
  all_branches boolean not null default false,
  unique (business_id, user_id),
  check (not all_branches or role in ('owner', 'manager')),
  check (role <> 'owner' or all_branches)
);

create table loyalty.staff_branches (
  business_id bigint not null,
  user_id uuid not null,
  branch_id bigint not null,
  primary key (business_id, user_id, branch_id),
  foreign key (business_id, user_id) references loyalty.staff_memberships (business_id, user_id),
  foreign key (business_id, branch_id) references public.branches
);

create table loyalty.programs (
  business_id bigint not null references loyalty.businesses,
  id bigint generated by default as identity,
  status text not null default 'draft' check (status in ('draft', 'active', 'paused', 'retired')),
  primary key (business_id, id)
);
create unique index programs_one_active on loyalty.programs (business_id) where status = 'active';

create table loyalty.program_versions (
  business_id bigint not null,
  program_id bigint not null,
  version integer not null check (version > 0),
  stamp_goal integer not null check (stamp_goal > 0),
  reward_description text not null check (btrim(reward_description) <> ''),
  inactivity_days integer check (inactivity_days > 0),
  primary key (business_id, program_id, version),
  foreign key (business_id, program_id) references loyalty.programs
);

-- Publish revised terms by inserting a version. Even the first concurrent use
-- sees a permanent snapshot, without depending on a future event writer to lock it.
create function loyalty.protect_program_version() returns trigger
language plpgsql set search_path = '' as $$
begin
  raise exception 'Program versions are immutable' using errcode = '23514';
end;
$$;
create trigger immutable_program_version before update or delete on loyalty.program_versions
for each row execute function loyalty.protect_program_version();

-- Contact is required, business-wide and one-to-one, so keep it on the customer.
create table loyalty.customers (
  business_id bigint not null,
  id bigint generated by default as identity,
  program_id bigint not null,
  display_name text not null check (btrim(display_name) <> ''),
  normalized_phone text not null check (normalized_phone ~ '^\+[1-9][0-9]{1,14}$'),
  email text,
  active boolean not null default true,
  marketing_consent boolean not null default false,
  primary key (business_id, id),
  unique (business_id, id, program_id),
  foreign key (business_id, program_id) references loyalty.programs
);

create table loyalty.marketing_consent_changes (
  id bigint generated always as identity primary key,
  business_id bigint not null,
  customer_id bigint not null,
  granted boolean not null,
  changed_at timestamptz not null default clock_timestamp(),
  foreign key (business_id, customer_id) references loyalty.customers
);

create function loyalty.record_consent_change() returns trigger
language plpgsql set search_path = '' as $$
begin
  insert into loyalty.marketing_consent_changes (business_id, customer_id, granted)
  values (new.business_id, new.id, new.marketing_consent);
  return null;
end;
$$;
create trigger initial_marketing_consent after insert on loyalty.customers
for each row when (new.marketing_consent) execute function loyalty.record_consent_change();
create trigger changed_marketing_consent after update of marketing_consent on loyalty.customers
for each row when (old.marketing_consent <> new.marketing_consent)
execute function loyalty.record_consent_change();

create table loyalty.pass_credentials (
  id bigint generated by default as identity primary key,
  business_id bigint not null,
  customer_id bigint not null,
  program_id bigint not null,
  token_hash bytea not null unique check (octet_length(token_hash) = 32),
  status text not null default 'issued' check (status in ('issued', 'rotated', 'revoked')),
  issued_at timestamptz not null default now(),
  ended_at timestamptz,
  check ((status = 'issued') = (ended_at is null)),
  check (ended_at >= issued_at),
  foreign key (business_id, customer_id, program_id)
    references loyalty.customers (business_id, id, program_id)
);

