-- The policy can call this private function without granting the API schema access.
create function loyalty.visible_branches() returns table (business_id bigint, branch_id bigint)
language sql stable security definer set search_path = '' as $$
  select b.business_id, b.id
  from loyalty.staff_memberships m
  join loyalty.businesses t on t.id = m.business_id and t.status = 'active'
  join public.branches b on b.business_id = m.business_id and b.active
  where m.user_id = (select auth.uid()) and m.active
    and m.role in ('owner', 'manager', 'branch_staff')
    and (m.all_branches or exists (
      select 1 from loyalty.staff_branches s
      where (s.business_id, s.user_id, s.branch_id) = (m.business_id, m.user_id, b.id)
    ))
$$;
alter function loyalty.visible_branches() owner to postgres;
revoke all on all functions in schema loyalty from public, anon, authenticated, service_role;
grant execute on function loyalty.visible_branches() to authenticated;

grant select (business_id, id, name) on public.branches to authenticated;
create policy read_assigned_active_branches on public.branches for select to authenticated
using ((business_id, id) in (select v.business_id, v.branch_id from loyalty.visible_branches() v));
